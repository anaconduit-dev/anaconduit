#!/bin/bash

# Останавливаем скрипт, если возникла критическая ошибка (кроме миграций)
set -e

echo "--- [1/2] Проверка структуры данных ---"
# Гарантируем наличие папок для SQLite и логов
mkdir -p /app/data/

echo "--- [2/2] Применение миграций БД ---"
# Пытаемся применить миграции. Если база новая, alembic создаст таблицы.
# Используем || true, чтобы контейнер не падал, если БД уже актуальна
alembic upgrade head || echo "ℹ️ Миграции не требуются или база уже обновлена"

echo "--- [🚀] Запуск Anaconduit API ---"
# Запускаем uvicorn через exec. 
# Это делает процесс python владельцем PID 1, что правильно для Docker
# (лучше пробрасываются сигналы остановки контейнера)
exec uvicorn app.main:app --host 0.0.0.0 --port 8000